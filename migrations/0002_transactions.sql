CREATE TABLE IF NOT EXISTS transactions (
  id TEXT PRIMARY KEY,
  user_id TEXT NOT NULL,
  property_id TEXT,
  transaction_ref TEXT NOT NULL,
  transaction_date TEXT NOT NULL,
  transaction_type TEXT NOT NULL DEFAULT 'Sale',
  property_type TEXT NOT NULL,
  property_title TEXT NOT NULL,
  property_address TEXT NOT NULL,
  locality TEXT NOT NULL DEFAULT '',
  city TEXT NOT NULL,
  state TEXT NOT NULL DEFAULT '',
  pincode TEXT NOT NULL DEFAULT '',
  buyer_name TEXT NOT NULL DEFAULT '',
  buyer_phone TEXT NOT NULL DEFAULT '',
  buyer_email TEXT NOT NULL DEFAULT '',
  seller_name TEXT NOT NULL DEFAULT '',
  seller_phone TEXT NOT NULL DEFAULT '',
  seller_email TEXT NOT NULL DEFAULT '',
  deal_value REAL NOT NULL DEFAULT 0,
  commission_rate REAL NOT NULL DEFAULT 0,
  commission_amount REAL NOT NULL DEFAULT 0,
  commission_status TEXT NOT NULL DEFAULT 'Pending',
  commission_paid REAL NOT NULL DEFAULT 0,
  commission_paid_date TEXT NOT NULL DEFAULT '',
  commission_invoice_no TEXT NOT NULL DEFAULT '',
  commission_invoice_date TEXT NOT NULL DEFAULT '',
  gst_amount REAL NOT NULL DEFAULT 0,
  tds_deducted REAL NOT NULL DEFAULT 0,
  broker_side TEXT NOT NULL DEFAULT 'Both',
  payment_method TEXT NOT NULL DEFAULT '',
  payment_reference TEXT NOT NULL DEFAULT '',
  transaction_status TEXT NOT NULL DEFAULT 'Closed',
  lead_source TEXT NOT NULL DEFAULT '',
  co_broker_name TEXT NOT NULL DEFAULT '',
  co_broker_share REAL NOT NULL DEFAULT 0,
  notes TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
  FOREIGN KEY(property_id) REFERENCES properties(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_transactions_user_date ON transactions(user_id, transaction_date DESC);
CREATE INDEX IF NOT EXISTS idx_transactions_property ON transactions(user_id, property_id);
